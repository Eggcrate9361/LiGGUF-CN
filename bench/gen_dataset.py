def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--outdir", default=os.path.dirname(os.path.abspath(__file__)))
    ap.add_argument("--seed", type=int, default=42)
    args = ap.parse_args()

    docs = [d for d, _ in DATA]
    queries = [q for _, q in DATA] + NOISE
    gt = [[str(i)] for i in range(len(DATA))] + [[] for _ in NOISE]

    assert len(docs) == 120 and len(queries) == 150 and len(gt) == 150

    for name, content in [("docs.txt", docs), ("queries.txt", queries)]:
        with open(os.path.join(args.outdir, name), "w", encoding="utf-8") as f:
            f.write("\n".join(content) + "\n")
    with open(os.path.join(args.outdir, "ground_truth.json"), "w", encoding="utf-8") as f:
        json.dump(gt, f, ensure_ascii=False, indent=1)

    print(f"OK: docs={len(docs)} queries={len(queries)} (incl. {len(NOISE)} noise) GT={sum(len(g)>0 for g in gt)}")


if __name__ == "__main__":
    main()